const SVG_PATH_NUMBER_PATTERN = /-?\d*\.?\d+(?:e[-+]?\d+)?/gi;

function clampProgress(progress: number): number {
  return Math.max(0, Math.min(1, progress));
}

function rounded(value: number): string {
  return String(Math.round(value * 1000) / 1000);
}

export function interpolateSvgPath(from: string, to: string, progress: number): string {
  const fromNumbers = (from.match(SVG_PATH_NUMBER_PATTERN) || []).map(Number);
  const toNumbers = (to.match(SVG_PATH_NUMBER_PATTERN) || []).map(Number);
  if (fromNumbers.length !== toNumbers.length) return to;
  const amount = clampProgress(progress);
  let index = 0;
  return to.replace(SVG_PATH_NUMBER_PATTERN, () => {
    const value = fromNumbers[index] + (toNumbers[index] - fromNumbers[index]) * amount;
    index += 1;
    return rounded(value);
  });
}

export function interpolateEyeMatrix(from: EyeMatrix, to: EyeMatrix, progress: number): EyeMatrix {
  const amount = clampProgress(progress);
  return from.map((value, index) => value + (to[index] - value) * amount) as unknown as EyeMatrix;
}

export function eyeMatrixAttribute(matrix: EyeMatrix): string {
  return `matrix(${matrix.map(rounded).join(' ')})`;
}


